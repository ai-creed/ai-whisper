#!/usr/bin/env node
// Generate packages/cli/src/generated/ezio-provenance.ts from the ezio checkout
// being bundled. Invoked before esbuild (bundle.mjs), before the suite (vitest
// globalSetup), and before tsc (typecheck scripts) so the statically-imported,
// gitignored module always exists and is inlined into the bundle. ALWAYS writes
// real provenance; FAILS LOUDLY if the ezio checkout cannot be resolved.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(here, ".."); // packages/cli
const OUT_FILE = path.join(PKG_ROOT, "src", "generated", "ezio-provenance.ts");

/** Pure: render the generated module source from a provenance object. */
export function renderProvenanceModule(p) {
	return [
		"// AUTO-GENERATED by scripts/stamp-ezio-provenance.mjs at build time. Do not edit.",
		"// Gitignored and regenerated each build/test/typecheck — never commit this file.",
		'import type { EzioProvenance } from "../ezio-provenance-types.js";',
		"",
		"export const EZIO_PROVENANCE: EzioProvenance = {",
		`\tezioCliVersion: ${JSON.stringify(p.ezioCliVersion)},`,
		`\tezioGitSha: ${JSON.stringify(p.ezioGitSha)},`,
		`\tbuiltAt: ${JSON.stringify(p.builtAt)},`,
		`\twhisperVersion: ${JSON.stringify(p.whisperVersion)},`,
		"};",
		"",
	].join("\n");
}

/** Pure-ish: gather provenance via injected IO seams. Throws if ezio is missing. */
export function collectProvenance({ pkgRoot, ezioRoot, now, readJson, gitShortSha }) {
	if (!ezioRoot) {
		throw new Error(
			"ezio checkout not found — cannot stamp provenance (build aborted; never ship an unstamped bundle).",
		);
	}
	const whisperVersion = readJson(path.join(pkgRoot, "package.json")).version;
	let ezioCliVersion;
	let ezioGitSha;
	try {
		ezioCliVersion = readJson(path.join(ezioRoot, "packages", "cli", "package.json")).version;
		ezioGitSha = gitShortSha(ezioRoot);
	} catch (err) {
		throw new Error(`ezio checkout at ${ezioRoot} is unreadable: ${err.message}`);
	}
	if (!ezioCliVersion) throw new Error(`ezio cli package.json has no version at ${ezioRoot}`);
	return { ezioCliVersion, ezioGitSha, builtAt: now().toISOString(), whisperVersion };
}

/**
 * Resolve the ezio repo root via the spec's `file:../ai-ezio` sibling layout:
 * pkgRoot (packages/cli) → repo root (../..) → sibling ai-ezio (../ai-ezio).
 * Returns null when the checkout is absent (→ collectProvenance fails loudly).
 * This is the same relative path pnpm uses for the `@ai-ezio/*` file: deps, so
 * it resolves wherever `pnpm install` does. Deliberately NOT require.resolve:
 * `@ai-ezio/harness` has no require-resolvable `exports`, so require.resolve
 * throws ERR_PACKAGE_PATH_NOT_EXPORTED in a normal checkout.
 */
export function findEzioRoot({ pkgRoot = PKG_ROOT, fileExists = existsSync } = {}) {
	const candidate = path.resolve(pkgRoot, "../../../ai-ezio");
	return fileExists(path.join(candidate, "packages", "cli", "package.json")) ? candidate : null;
}

function defaultReadJson(p) {
	return JSON.parse(readFileSync(p, "utf8"));
}
function defaultGitShortSha(repo) {
	return execFileSync("git", ["-C", repo, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
}

/** Side-effecting entry used by bundle.mjs, the vitest globalSetup, and the CLI. */
export function generate() {
	const p = collectProvenance({
		pkgRoot: PKG_ROOT,
		ezioRoot: findEzioRoot(),
		now: () => new Date(),
		readJson: defaultReadJson,
		gitShortSha: defaultGitShortSha,
	});
	mkdirSync(path.dirname(OUT_FILE), { recursive: true });
	writeFileSync(OUT_FILE, renderProvenanceModule(p), "utf8");
	return p;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const p = generate();
	console.log(`stamp: ezio ${p.ezioCliVersion} (${p.ezioGitSha}), whisper ${p.whisperVersion}`);
}
